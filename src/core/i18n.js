export const UI_LANGS = [
  { id: 'ru', title: 'Рус', locale: 'ru-RU', name: 'Русский' },
  { id: 'en', title: 'Eng', locale: 'en-US', name: 'English' },
];

const DEFAULT_LANG = 'ru';

const CYRILLIC_UI = new Set(['ru', 'uk', 'be', 'kk', 'ky', 'bg', 'mk', 'sr']);

export function detectLang(hint) {
  const raw = hint ?? (typeof navigator !== 'undefined' ? navigator.language : '');
  const base = String(raw || '').split('-')[0].toLowerCase();
  return CYRILLIC_UI.has(base) ? 'ru' : 'en';
}

let current = DEFAULT_LANG;

export function setLang(id) {
  const next = UI_LANGS.some((item) => item.id === id) ? id : DEFAULT_LANG;
  if (next === current) return false;
  current = next;
  return true;
}

export function lang() {
  return current;
}

export function locale() {
  return UI_LANGS.find((item) => item.id === current)?.locale || 'ru-RU';
}

function formIndex(n, language = current) {
  if (language !== 'ru') return n === 1 ? 0 : 1;
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return 0;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 1;
  return 2;
}

const HOLE = /\{(\w+)\}/g;

function fill(template, params) {
  if (!params) return template;
  return template.replace(HOLE, (whole, name) => (name in params ? String(params[name]) : whole));
}

export function t(key, params) {
  const value = DICT[current]?.[key] ?? DICT[DEFAULT_LANG]?.[key];
  if (value === undefined) return key;
  const template = Array.isArray(value) ? value[formIndex(params?.n ?? 0)] : value;
  return fill(template ?? key, params);
}

export function has(key) {
  return DICT[current]?.[key] !== undefined || DICT[DEFAULT_LANG]?.[key] !== undefined;
}

const displayNames = new Map();

function names() {
  const key = current;
  if (!displayNames.has(key)) {
    try {
      displayNames.set(key, new Intl.DisplayNames([locale()], { type: 'language' }));
    } catch {
      displayNames.set(key, null);
    }
  }
  return displayNames.get(key);
}

function capitalize(text) {
  return text ? text[0].toUpperCase() + text.slice(1) : text;
}

const NAME_OVERRIDE = {
  ru: { 'zh-Hans': 'Китайский упр.', 'zh-Hant': 'Китайский трад.' },
  en: { 'zh-Hans': 'Chinese, simpl.', 'zh-Hant': 'Chinese, trad.' },
};

export function languageName(code) {
  const custom = NAME_OVERRIDE[current]?.[code];
  if (custom) return custom;
  const found = names()?.of(code);
  if (!found || found === code) return code.toUpperCase();
  return capitalize(found);
}

export function compareNames(a, b) {
  return a.localeCompare(b, locale());
}

